// Renders a car's spin layers with Blender on a free Kaggle GPU notebook, then downloads them to models-src/spin-raw/<id>/.
// Needs KAGGLE_USERNAME and KAGGLE_KEY in .env.local (kaggle.com > Settings > API), and a phone-verified Kaggle account.
// Usage: node render/spin-kaggle.mjs <model-id> [--only 3,6] [--samples 256] [--light 1] [--device CUDA] [--fresh]
// Then:  node dev/pack-spin.mjs <model-id>
// The raw model goes into a private Kaggle dataset (lw-src-<id>); the notebook (lw-render-<id>) is private too.
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { MODELS } from '../shared/catalog.js';

if (fs.existsSync('.env.local')) process.loadEnvFile('.env.local');
const [id, ...rest] = process.argv.slice(2);
const opt = (name, def) => (rest.includes(`--${name}`) ? rest[rest.indexOf(`--${name}`) + 1] : def);
const spec = MODELS.find((m) => m.id === id);
const recipe = JSON.parse(fs.readFileSync('dev/recipes.json', 'utf8'))[id];
const glb = `models-src/${id}.glb`;
if (!spec || !recipe || !fs.existsSync(glb)) throw new Error(`Need a catalog entry, a dev/recipes.json entry and ${glb} for "${id}"`);
const USER = process.env.KAGGLE_USERNAME;
const KEY = process.env.KAGGLE_KEY;
if (!USER || !KEY) throw new Error('Set KAGGLE_USERNAME and KAGGLE_KEY in .env.local');

const API = 'https://www.kaggle.com/api/v1';
const AUTH = KEY.startsWith('KGAT_') ? `Bearer ${KEY}` : `Basic ${Buffer.from(`${USER}:${KEY}`).toString('base64')}`;
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
async function api(method, url, body) {
  for (let attempt = 0; ; attempt++) {
    const r = await fetch(API + url, { method, headers: { Authorization: AUTH, 'Content-Type': 'application/json' }, body: body && JSON.stringify(body) });
    const text = await r.text();
    if (r.status >= 500 && attempt < 4) { await sleep(5000); continue; }
    let json;
    try { json = JSON.parse(text); } catch { json = text; }
    if (!r.ok) throw Object.assign(new Error(`Kaggle ${method} ${url} -> ${r.status} ${text.slice(0, 400)}`), { status: r.status });
    if (json?.error) throw new Error(`Kaggle ${method} ${url}: ${json.error}`);
    return json;
  }
}

// ---- 1. raw model -> private dataset (skipped when this exact file is already there) --------------------------
const BLENDER = '4.2.3';
const dsSlug = `lw-src-${id}`;
const rawDir = path.resolve(`models-src/spin-raw/${id}`);
fs.mkdirSync(rawDir, { recursive: true });
const stat = fs.statSync(glb);
const marker = path.join(rawDir, '.kaggle.json');
const stamp = `${stat.size}:${Math.round(stat.mtimeMs)}`;
const have = fs.existsSync(marker) ? JSON.parse(fs.readFileSync(marker, 'utf8')) : {};
const started = Date.now();
if (!rest.includes('--fetch') && (have.stamp !== stamp || rest.includes('--fresh'))) {
  console.log(`Uploading ${glb} (${(stat.size / 1e6).toFixed(1)} MB) to the private dataset ${USER}/${dsSlug}...`);
  const blob = await api('POST', '/blobs/upload', { type: 'DATASET', name: 'car.glb', contentLength: stat.size, lastModifiedEpochSeconds: Math.round(stat.mtimeMs / 1000) });
  const put = await fetch(blob.createUrl, { method: 'PUT', headers: { 'Content-Type': 'application/octet-stream' }, body: fs.readFileSync(glb) });
  if (!put.ok) throw new Error(`Upload failed: ${put.status} ${(await put.text()).slice(0, 300)}`);
  let exists = true;
  try { await api('GET', `/datasets/status/${USER}/${dsSlug}`); } catch { exists = false; }
  if (exists) await api('POST', `/datasets/create/version/${USER}/${dsSlug}`, { versionNotes: 'update', files: [{ token: blob.token }], deleteOldVersions: true });
  else await api('POST', '/datasets/create/new', { ownerSlug: USER, slug: dsSlug, title: `LW src ${id}`, licenseName: 'unknown', isPrivate: true, files: [{ token: blob.token }] });
  for (let i = 0; ; i++) {
    await sleep(5000);
    const s = await api('GET', `/datasets/status/${USER}/${dsSlug}`).catch(() => 'pending');
    if (String(s?.status ?? s).toLowerCase().includes('ready')) break;
    if (i > 60) throw new Error(`Dataset still not ready: ${JSON.stringify(s)}`);
  }
  fs.writeFileSync(marker, JSON.stringify({ stamp }));
}

// ---- 2. notebook script: fetch Blender, render, tar the layers -------------------------------------------------
const b64 = (file) => fs.readFileSync(file).toString('base64');
const args = ['--glb', 'GLB', '--recipe', '/tmp/lw/recipe.json', '--dims', spec.dims.slice(0, 3).join(','), '--out', '/tmp/lw/out', '--hdri', '/tmp/lw/studio.hdr', '--device', opt('device', 'CUDA')];
for (const k of ['only', 'samples', 'light', 'frames', 'width', 'height']) if (opt(k)) args.push(`--${k}`, opt(k));
const script = `# Legacy Wraps spin render: ${id} (generated by render/spin-kaggle.mjs)
import base64, glob, json, os, subprocess, tarfile, time
T = '/tmp/lw'
os.makedirs(T + '/out', exist_ok=True)
open(T + '/scene.py', 'wb').write(base64.b64decode('${b64('render/scene.py')}'))
open(T + '/recipe.json', 'wb').write(base64.b64decode('${Buffer.from(JSON.stringify(recipe)).toString('base64')}'))
t0 = time.time()
def sh(cmd):
    print('LW $', cmd[:110], flush=True)
    return subprocess.run(cmd, shell=True).returncode
sh('nvidia-smi --query-gpu=name,memory.total --format=csv,noheader')
sh('apt-get install -y -qq libxi6 libxxf86vm1 libxfixes3 libxrender1 libxkbcommon0 libsm6 libice6 libgl1 libegl1 >/dev/null 2>&1')
status = {'code': 1, 'step': 'download'}
ok = sh('curl -fsSL https://download.blender.org/release/Blender${BLENDER.slice(0, 3)}/blender-${BLENDER}-linux-x64.tar.xz | tar -xJ -C ' + T) == 0
ok = ok and sh('curl -fsSL -o ' + T + '/studio.hdr https://dl.polyhaven.org/file/ph-assets/HDRIs/hdr/2k/studio_small_09_2k.hdr') == 0
glbs = glob.glob('/kaggle/input/**/car.glb', recursive=True)
print('LW inputs', glbs, flush=True)
if ok and glbs:
    status['step'] = 'render'
    args = ${JSON.stringify(args)}
    args[1] = glbs[0]
    p = subprocess.Popen([T + '/blender-${BLENDER}-linux-x64/blender', '-b', '--python-exit-code', '1', '-P', T + '/scene.py', '--'] + args, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True, errors='replace')
    with open('/kaggle/working/blender.log', 'w') as log:
        for line in p.stdout:
            log.write(line)
            if line.startswith('LW ') or 'Error' in line or 'Traceback' in line:
                print(line.rstrip(), flush=True)
    status['code'] = p.wait()
    if status['code'] == 0 and not os.path.exists(T + '/out/meta.json'):
        status['code'] = 2
    if status['code'] == 0:
        status['step'] = 'done'
        with tarfile.open('/kaggle/working/out.tar', 'w') as tar:
            tar.add(T + '/out', arcname='.')
status['seconds'] = round(time.time() - t0)
json.dump(status, open('/kaggle/working/status.json', 'w'))
print('LW status', status, flush=True)
`;

const slug = `lw-render-${id}`;
// --fetch: only download the last run's output (e.g. after a dropped connection), no new render.
const FETCH_ONLY = rest.includes('--fetch');
const pushed = FETCH_ONLY ? { versionNumber: '(existing)', url: slug } : await api('POST', '/kernels/push', {
  slug: `${USER}/${slug}`, newTitle: `LW render ${id}`, text: script, language: 'python', kernelType: 'script',
  isPrivate: true, enableGpu: opt('device', 'CUDA') !== 'CPU', enableInternet: true,
  machineShape: opt('device', 'CUDA') === 'CPU' ? undefined : opt('machine', 'NvidiaTeslaT4'),
  datasetDataSources: [`${USER}/${dsSlug}`], competitionDataSources: [], kernelDataSources: [], modelDataSources: [], categoryIds: [],
});
console.log(`Notebook version ${pushed.versionNumber ?? '?'} queued: ${pushed.url || slug}`);

// ---- 3. wait, then download ------------------------------------------------------------------------------------
const q = `userName=${encodeURIComponent(USER)}&kernelSlug=${slug}`;
let last = '';
for (;;) {
  await sleep(20_000);
  const s = await api('GET', `/kernels/status?${q}`).catch((e) => ({ status: `(${e.message.slice(0, 80)})` }));
  const state = String(s.status).toLowerCase();
  if (state !== last) console.log(`  ${state} (${Math.round((Date.now() - started) / 1000)}s)`);
  last = state;
  if (/complete|error|cancel/.test(state)) { if (s.failureMessage) console.log('  ' + s.failureMessage); break; }
}
const files = [];
let log = '';
for (let token = ''; ; ) {
  const out = await api('GET', `/kernels/output?${q}${token ? `&pageToken=${encodeURIComponent(token)}` : ''}`);
  files.push(...(out.files || []));
  log ||= out.log || '';
  token = out.nextPageToken;
  if (!token) break;
}
let lines = [];
try { lines = JSON.parse(log).map((l) => String(l.data ?? '').trimEnd()); } catch { lines = log.split('\n'); }
for (const l of lines) if (/^LW |Error|Traceback/.test(l)) console.log(l);
const get = async (name) => {
  const f = files.find((x) => x.fileName === name);
  if (!f) return null;
  // Large outputs over a phone or home connection can drop mid-way; retry a few times.
  for (let attempt = 1; ; attempt++) {
    try {
      const r = await fetch(f.url);
      if (!r.ok) throw new Error(`Download ${name}: ${r.status}`);
      return Buffer.from(await r.arrayBuffer());
    } catch (e) {
      if (attempt >= 5) throw e;
      console.log(`  download of ${name} failed (${e.message}), retrying ${attempt}/4...`);
      await sleep(5000 * attempt);
    }
  }
};
const blenderLog = await get('blender.log');
if (blenderLog) fs.writeFileSync(path.join(rawDir, '_blender.log'), blenderLog);
const tar = await get('out.tar');
if (!tar) {
  console.log(lines.slice(-25).join('\n'));
  if (blenderLog) console.log('--- blender.log tail ---\n' + blenderLog.toString().split('\n').slice(-40).join('\n'));
  throw new Error('Render failed (no out.tar). Full Blender log: ' + path.join(rawDir, '_blender.log'));
}
fs.writeFileSync(path.join(rawDir, '_out.tar'), tar);
execFileSync('tar', ['-xf', '_out.tar'], { cwd: rawDir });
fs.rmSync(path.join(rawDir, '_out.tar'));
console.log(`Done in ${Math.round((Date.now() - started) / 1000)}s -> ${rawDir}`);
