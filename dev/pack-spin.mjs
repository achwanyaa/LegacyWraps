// Packs raw spin renders (models-src/spin-raw/<id>/, from render/spin.mjs) into phone-friendly WebP in public/spins/<id>/
// and regenerates shared/spins.js. Usage: node dev/pack-spin.mjs [id ...]
import fs from 'node:fs';
import path from 'node:path';
import sharp from 'sharp';

const SIZES = [480, 800, 1280]; // spin set, phone sharp, desktop sharp
const rawRoot = 'models-src/spin-raw';
const credits = JSON.parse(fs.readFileSync('models-src/credits.json', 'utf8'));
const manifestPath = path.resolve('shared/spins.js');
const prev = fs.existsSync(manifestPath) ? (await import(`../shared/spins.js?${Date.now()}`)).SPINS : {};
const only = process.argv.slice(2);
const manifest = {};

for (const id of fs.existsSync(rawRoot) ? fs.readdirSync(rawRoot) : []) {
  const dir = path.join(rawRoot, id);
  if (!fs.existsSync(path.join(dir, 'meta.json'))) continue;
  if (only.length && !only.includes(id)) {
    if (prev[id]) manifest[id] = prev[id];
    continue;
  }
  const meta = JSON.parse(fs.readFileSync(path.join(dir, 'meta.json'), 'utf8'));
  const rows = meta.tiles.length / meta.cols;
  const count = meta.frames + (meta.top ? 1 : 0);
  const kb = {};
  for (const size of SIZES) {
    const out = path.resolve(`public/spins/${id}/${size}`);
    fs.mkdirSync(out, { recursive: true });
    const w = Math.min(size, meta.width);
    const h = Math.round((w * meta.height) / meta.width);
    let bytes = 0;
    for (let f = 0; f < count; f++) {
      const n = String(f).padStart(2, '0');
      const baseSrc = path.join(dir, `base_${n}.png`);
      if (!fs.existsSync(baseSrc)) throw new Error(`${id}: frame ${n} has not been rendered`);
      const base = path.join(out, `b-${n}.webp`);
      await sharp(baseSrc).resize(w, h).webp({ quality: 82, alphaQuality: 90, effort: 5 }).toFile(base);
      // Resize every tile on its own so neighbours don't bleed into each other, then rebuild the grey atlas.
      const tiles = [];
      for (let t = 0; t < meta.tiles.length; t++) {
        const input = await sharp(path.join(dir, `layers_${n}.png`))
          .extract({ left: (t % meta.cols) * meta.width, top: Math.floor(t / meta.cols) * meta.height, width: meta.width, height: meta.height })
          .resize(w, h)
          .png()
          .toBuffer();
        tiles.push({ input, left: (t % meta.cols) * w, top: Math.floor(t / meta.cols) * h });
      }
      const layers = path.join(out, `l-${n}.webp`);
      await sharp({ create: { width: w * meta.cols, height: h * rows, channels: 3, background: '#000' } })
        .composite(tiles)
        .greyscale()
        .webp({ quality: 84, effort: 5 })
        .toFile(layers);
      bytes += fs.statSync(base).size + fs.statSync(layers).size;
    }
    kb[size] = Math.round(bytes / count / 1024);
  }
  const c = credits[id] || {};
  manifest[id] = {
    path: `/spins/${id}`,
    frames: meta.frames,
    top: !!meta.top,
    sizes: SIZES,
    aspect: meta.width / meta.height,
    tiles: meta.tiles,
    cols: meta.cols,
    scale: meta.scale,
    zones: meta.zones,
    kb,
    credit: { title: c.title, author: c.author, license: c.license, url: c.url },
  };
  console.log(`${id}: ${count} angles, ${kb[480]} KB at 480, ${kb[800]} KB at 800, ${kb[1280]} KB at 1280 per angle, zones: ${meta.zones.join(', ')}`);
}

fs.writeFileSync(manifestPath, `// Generated by dev/pack-spin.mjs — cars with pre-rendered spin layers.\nexport const SPINS = ${JSON.stringify(manifest, null, 2)};\n`);
